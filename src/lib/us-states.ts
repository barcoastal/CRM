/** Normalize any state input ("Hawaii", "hi", " HI ") to the 2-letter code, or "" if unknown. */
export function normalizeUsState(input: string | null | undefined): string {
  if (!input) return "";
  const s = input.trim().toLowerCase();
  if (!s) return "";
  const byCode = US_STATES.find((st) => st.code.toLowerCase() === s);
  if (byCode) return byCode.code;
  const byName = US_STATES.find((st) => st.name.toLowerCase() === s);
  return byName ? byName.code : "";
}

/** True for 5-digit or ZIP+4 codes. */
export function isValidUsZip(zip: string | null | undefined): boolean {
  return !!zip && /^\d{5}(-\d{4})?$/.test(zip.trim());
}

/** Format a US phone for display: (615) 335-4171. Leaves non-US-shaped input as-is. */
export function formatUsPhone(phone: string | null | undefined): string {
  if (!phone) return "";
  const digits = phone.replace(/\D/g, "");
  const ten = digits.length === 11 && digits.startsWith("1") ? digits.slice(1) : digits;
  if (ten.length !== 10) return phone;
  return `(${ten.slice(0, 3)}) ${ten.slice(3, 6)}-${ten.slice(6)}`;
}
